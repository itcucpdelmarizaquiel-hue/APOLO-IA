import assert from "node:assert/strict";
import { createServer } from "node:http";
import { test } from "node:test";
import express from "express";
import { createImageGenerationHandler } from "../server/image-generation";

type Dependencies = Parameters<typeof createImageGenerationHandler>[0];

async function withImageApi(
  dependencies: Dependencies,
  callback: (url: string) => Promise<void>,
) {
  const app = express();
  app.use(express.json());
  app.post("/api/gemini/generate-image", createImageGenerationHandler(dependencies));
  const server = createServer(app);
  server.listen(0, "127.0.0.1");
  await new Promise<void>((resolve) => server.once("listening", resolve));
  const address = server.address();
  assert.ok(address && typeof address !== "string");

  try {
    await callback(`http://127.0.0.1:${address.port}/api/gemini/generate-image`);
  } finally {
    await new Promise<void>((resolve, reject) => {
      server.close((error) => error ? reject(error) : resolve());
    });
  }
}

async function postImage(url: string, body: Record<string, unknown> = { prompt: "Uma cidade ao pôr do sol" }) {
  const response = await fetch(url, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  return { response, data: await response.json() as Record<string, any> };
}

test("returns an image generated by Gemini with the requested options", async () => {
  let imageOptions: Record<string, any> | undefined;
  const ai = {
    models: {
      generateContent: async (options: Record<string, any>) => {
        if (options.model.endsWith("-image")) {
          imageOptions = options;
          return {
            candidates: [{
              content: {
                parts: [{ inlineData: { mimeType: "image/png", data: "aW1hZ2U=" } }],
              },
            }],
          };
        }
        return { text: "A cinematic sunset city" };
      },
    },
  };

  await withImageApi({
    getGeminiClient: () => ai,
    fetchPollinations: async () => {
      throw new Error("Pollinations should not be used for a Gemini image");
    },
  }, async (url) => {
    const { response, data } = await postImage(url, {
      prompt: "Uma cidade ao pôr do sol",
      aspectRatio: "3:4",
      imageSize: "2K",
      seed: 42,
    });

    assert.equal(response.status, 200);
    assert.equal(data.success, true);
    assert.equal(data.source, "gemini-image-engine");
    assert.equal(data.imageUrl, "data:image/png;base64,aW1hZ2U=");
    assert.equal(data.aspectRatio, "3:4");
    assert.equal(data.imageSize, "2K");
    assert.equal(data.seed, 42);
    assert.equal(imageOptions?.config.imageConfig.aspectRatio, "3:4");
    assert.equal(imageOptions?.config.imageConfig.imageSize, "2K");
  });
});

test("rejects empty prompts and invalid ratio, size, and seed before calling providers", async () => {
  let providerCalls = 0;
  const cases = [
    { prompt: "  " },
    { prompt: "x".repeat(4001) },
    { prompt: "city", aspectRatio: "2:1" },
    { prompt: "city", imageSize: "8K" },
    { prompt: "city", seed: -1 },
    { prompt: "city", seed: 1.5 },
    { prompt: "city", seed: "42" },
  ];

  await withImageApi({
    getGeminiClient: () => {
      providerCalls += 1;
      return null;
    },
    fetchPollinations: async () => {
      providerCalls += 1;
      return new Response(null, { headers: { "content-type": "image/png" } });
    },
  }, async (url) => {
    for (const body of cases) {
      const { response, data } = await postImage(url, body);
      assert.equal(response.status, 400, JSON.stringify(body));
      assert.equal(typeof data.error, "string");
    }
  });

  assert.equal(providerCalls, 0);
});

test("falls back to Pollinations when Gemini cannot return an image", async () => {
  let pollinationsUrl = "";
  const ai = {
    models: {
      generateContent: async ({ model }: Record<string, any>) => {
        if (model.endsWith("-image")) throw new Error("Gemini image service unavailable");
        return { text: "translated city prompt" };
      },
    },
  };

  await withImageApi({
    getGeminiClient: () => ai,
    createSeed: () => 314,
    fetchPollinations: async (url) => {
      pollinationsUrl = String(url);
      return new Response(new Uint8Array([1, 2, 3]), {
        status: 200,
        headers: { "content-type": "image/jpeg" },
      });
    },
  }, async (url) => {
    const { response, data } = await postImage(url, {
      prompt: "Uma cidade ao pôr do sol",
      aspectRatio: "16:9",
    });

    assert.equal(response.status, 200);
    assert.equal(data.success, true);
    assert.equal(data.source, "apolo-flux-engine");
    assert.equal(data.seed, 314);
    assert.match(data.imageUrl, /^data:image\/jpeg;base64,/);
    assert.match(data.imageUrl, /AQID$/);
    assert.match(pollinationsUrl, /^https:\/\/image\.pollinations\.ai\/prompt\//);
    assert.match(pollinationsUrl, /width=1280&height=720&seed=314/);
  });
});

test("returns an actionable error when the fallback network request fails", async () => {
  await withImageApi({
    getGeminiClient: () => null,
    fetchPollinations: async () => {
      throw new TypeError("fetch failed");
    },
  }, async (url) => {
    const { response, data } = await postImage(url);
    assert.equal(response.status, 502);
    assert.equal(typeof data.error, "string");
    assert.match(data.error, /Verifique a conexão e tente novamente/);
    assert.equal(data.imageUrl, undefined);
  });
});

test("does not report success when Pollinations responds with an error", async () => {
  await withImageApi({
    getGeminiClient: () => null,
    fetchPollinations: async () => new Response("unavailable", { status: 503 }),
  }, async (url) => {
    const { response, data } = await postImage(url);
    assert.equal(response.status, 502);
    assert.equal(typeof data.error, "string");
    assert.equal(data.imageUrl, undefined);
  });
});
